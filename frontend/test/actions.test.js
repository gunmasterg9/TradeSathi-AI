import test from 'node:test'
import assert from 'node:assert/strict'

test('Export Brief generator creates standard trade briefing format', () => {
  const mockResult = {
    id: 'anl-999',
    mode: 'rules_fallback',
    model: null,
    summary: {
      status: 'needs_attention',
      headline: 'Reconciliation completed with 1 discrepancy',
      documents_received: ['commercial_invoice.txt', 'packing_list.txt'],
      summary_text: 'Net weight mismatch detected.',
      checklist: [
        { id: 'chk-weights', status: 'failed', title: 'Weights & Cargo Tally', detail: 'Net weight mismatch of 100 kg' },
        { id: 'chk-entities', status: 'passed', title: 'Parties & Entities', detail: 'Consistent shipper' },
      ],
    },
    discrepancies: [
      {
        field: 'total_net_weight_kg',
        label: 'Net Weight',
        severity: 'warning',
        message: 'commercial_invoice: 18000 kg vs packing_list: 18100 kg',
        recommended_action: 'Perform physical weighment before export.',
      },
    ],
  }

  const discText = mockResult.discrepancies
    .map((d) => `• [${d.severity.toUpperCase()}] ${d.label}: ${d.message}\n  Action: ${d.recommended_action}`)
    .join('\n')

  const chkText = mockResult.summary.checklist
    .map((c) => `• [${c.status.toUpperCase().replace('_', ' ')}] ${c.title}: ${c.detail}`)
    .join('\n')

  const brief = `=== TRADESATHI AI SHIPMENT AUDIT BRIEF ===
ID: ${mockResult.id}
Status: ${mockResult.summary.status.toUpperCase()}
Mode: ${mockResult.mode} (${mockResult.model || 'Deterministic Rules'})
Documents: ${mockResult.summary.documents_received.join(', ')}

Headline: ${mockResult.summary.headline}
Summary: ${mockResult.summary.summary_text}

OPERATIONAL REVIEW CHECKLIST:
${chkText}

DISCREPANCIES & HUMAN VERIFICATION ACTIONS:
${discText}

Note: Generated by TradeSathi AI. Human sign-off required prior to customs lodgement.`

  assert.match(brief, /=== TRADESATHI AI SHIPMENT AUDIT BRIEF ===/)
  assert.match(brief, /ID: anl-999/)
  assert.match(brief, /Status: NEEDS_ATTENTION/)
  assert.match(brief, /Net Weight: commercial_invoice: 18000 kg vs packing_list: 18100 kg/)
  assert.match(brief, /Action: Perform physical weighment before export\./)
  assert.match(brief, /Weights & Cargo Tally/)
})

test('JSON export serializes complete audit object without data loss', () => {
  const auditData = {
    id: 'anl-12345',
    created_at: new Date().toISOString(),
    mode: 'rules_fallback',
    summary: { status: 'needs_attention' },
    discrepancies: [{ field: 'total_net_weight_kg', difference: '+100 kg' }],
    documents: [{ filename: 'commercial_invoice.txt', total_net_weight_kg: 18000 }],
  }

  const jsonString = JSON.stringify(auditData, null, 2)
  const parsed = JSON.parse(jsonString)

  assert.equal(parsed.id, 'anl-12345')
  assert.equal(parsed.discrepancies[0].difference, '+100 kg')
  assert.equal(parsed.documents[0].total_net_weight_kg, 18000)
})
